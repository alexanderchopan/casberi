def self_test(verbose=True):
    ok = True

    def check(why, got):
        nonlocal ok
        if not got:
            ok = False
        if verbose or not got:
            print(f"  {'ok  ' if got else 'FAIL'} {why}")

    sections, by_num, dead, notes, renames = compute(FIXTURE)
    live = {s["num"] for s in sections if s["num"] not in dead}
    n = lambda num: notes.get(num, [])

    check("a bare index row kills the ruling (§61 superseded by §97)", "61" not in live)
    check("two verbs in one cell both land ('superseded by §97, reversed by §114')",
          set(dead.get("61", [])) == {"97", "114"})
    check("a row naming the ruling by its own title kills it (§1001)", "1001" not in live)
    check("a heading's 'supersedes §1001' kills it too, four digits", "1008" in dead.get("1001", []))
    check("a later supersede of the killer kills the killer (§1008 by §1012)", "1008" not in live)
    check("a clause-qualified row leaves the ruling live (§306 (quiet hours))",
          "306" in live and ("part superseded", "870") in n("306"))
    check("'superseded in part by' is a clause, not a death (§606 → §692)",
          ("part superseded", "692") in n("606"))
    check("'superseded by §941 in the Wallet' is a clause (§940 stays live)",
          "940" in live and ("part superseded", "941") in n("940"))
    check("'amended … for ONE event' is a chain link (§500 → §522)", ("amended", "522") in n("500"))
    check("a qualifier sharing most of the title's words is still a clause (§937 stands)",
          "937" in live and ("part superseded", "958") in n("937"))
    check("a subject before the verb is a clause ('default reversed by', 'the glass tray … deleted by')",
          "393" in live and {("part superseded", "393a"), ("part superseded", "712")} <= set(n("393")))
    check("a bare row whose 'What it said' is not the title is a clause (§57's Telegram half)",
          "57" in live and ("part superseded", "456") in n("57"))
    check("'…; §775 is in turn superseded by §904' is about §775, not this row's §760",
          "760" in live and all(b != "904" for _, b in n("760")) and ("amended", "775") in n("760"))
    check("a qualifier that merely shares the title's words is a clause ('the box gives way')",
          "772" in live and ("part superseded", "904") in n("772"))
    check("…and the row's own top-level verb still lands (§772 amended by §775)",
          ("amended", "775") in n("772"))
    check("Known stale, verbless ('§100 — …') kills a ruling named by its title (§16)",
          "16" not in live and dead.get("16") == ["100"])
    check("Known stale 'tail order' clause is an amendment chain link (§548 → §688)",
          "548" in live and any(b == "688" for _, b in n("548")))
    check("a pure renumber row is a rename, not a death (§236 → §236b)",
          renames.get("236") == "236b" and "236b" in live)
    check("a non-rename row in the Renumbered table is still read (§983 item 2 → §985)",
          "983" in live and any(b == "985" for _, b in n("983")))
    check("pre-§ heading spelling 'supersedes 36a/36j' kills both",
          "36a" not in live and "36j" not in live and "36o" in live)
    check("'amends 36a' in a heading is a chain link, not a death", ("amended", "36j") in n("36a"))
    check("a possessive clause in a heading ('§969's \"never opened…\"') leaves §969 live",
          "969" in live and ("part superseded", "981") in n("969"))
    check("one heading, two verbs: 'supersedes §1008, amends §1011, §976a and §958'",
          all(("amended", "1012") in n(x) for x in ("1011", "976a", "958")))
    check("'retires §500 and §606' kills both (the seat-retirement shape)",
          "500" not in live and "606" not in live)
    check("a heading that says it was itself 'superseded the next day by §969' is dead",
          "961" not in live and dead.get("961") == ["969"])
    check("an amendment H2 is counted on its parent, not listed as a ruling",
          sum(1 for s in sections if s["num"] == "319") == 1 and by_num["319"]["subs"] == 2)
    check("a heading's trailing user quote is stripped from its title",
          by_num["772"]["title"] == "The lead ladder, and the box gives way" and by_num["1001"]["title"] == "The tray's marks stay on the row size")
    kept = compute(FIXTURE, {"61": "test"})
    check("a LIVE_DESPITE_INDEX entry keeps an over-claimed ruling live, chain kept",
          "61" not in kept[2] and ("part superseded", "97") in kept[3].get("61", []))
    check("a bare '## §536' heading takes its body's bold lead as its title",
          by_num["536"]["title"] == "Polar lands SALES")
    out, stats = render(FIXTURE)
    check("the render lists a live ruling with its chain",
          "- §772 — The lead ladder, and the box gives way (amended by §775; part superseded by §904)" in out)
    check("the render never lists a dead ruling as live", "\n- §61 — " not in out)
    check("the dead list points a dead ruling at its replacement", "§1001→§1008" in out)
    bad = check_hand_half("## Design\n\n- The tray marks are 28pt (§1001).\n\n## Conflicts to resolve\n\n- §61 vs §114\n",
                          stats["dead_set"])
    check("--check flags a by-area rule citing a dead ruling, and not the Conflicts list",
          [b[0] for b in bad] == ["1001"])
    return ok


