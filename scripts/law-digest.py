def main(argv):
    if "--self-test" in argv:
        print("law-digest self-test")
        return 0 if self_test() else 1
    if not self_test(verbose=False):
        print("✗ law-digest: SELF-TEST FAILED — not writing a digest the parser cannot stand behind")
        return 1
    text = LEDGER.read_text(encoding="utf-8")
    generated, stats = render(text, LIVE_DESPITE_INDEX)
    existing = LAW.read_text(encoding="utf-8") if LAW.exists() else ""
    hand = existing.split(MARKER)[0] if MARKER in existing else (existing or DEFAULT_HEAD)
    hand = hand.rstrip("\n") + "\n\n"
    stale = check_hand_half(hand, stats["dead_set"])
    summary = (f"{stats['live']} live of {stats['total']} rulings · {stats['dead']} dead · "
               f"{stats['amended']} live with an amendment chain · {stats['part']} part superseded")
    if "--stats" in argv:
        print(summary)
        return 0
    new = hand + generated
    if "--check" in argv:
        problems = []
        if existing != new:
            problems.append("docs/law.md is stale — run `python3 scripts/law-digest.py`")
        for num, line in stale:
            problems.append(f"the by-area half cites §{num}, which the ledger records as dead: {line}")
        if problems:
            print("✗ law digest:")
            for p in problems:
                print(f"  {p}")
            return 1
        print(f"✓ law digest current: {summary}")
        return 0
    LAW.write_text(new, encoding="utf-8")
    print(f"wrote {LAW.relative_to(ROOT)} ({len(new.encode('utf-8')) // 1024} KB): {summary}")
    for num, line in stale:
        print(f"  ! by-area rule cites dead §{num}: {line}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
