def strip_trailing_paren(title):
    """Split "Title (user: "…", 2026-09-29; supersedes §X)" into the title and
    the trailing parenthetical. The trailing group is the one whose opening
    paren closes exactly at the end of the line; quotes inside it may hold
    balanced parens of their own, so the walk counts depth."""
    t = title.rstrip()
    if not t.endswith(")"):
        # A truncated or unbalanced heading: fall back to the first " (user"
        # / " (20xx-" / " (same canvas" opening.
        m = re.search(r"\s\((?:user|20\d\d-|same |the |ruling|amend|Option)", t)
        return (t[:m.start()].rstrip(), t[m.start():]) if m else (t, "")
    depth = 0
    for i in range(len(t) - 1, -1, -1):
        c = t[i]
        if c == ")":
            depth += 1
        elif c == "(":
            depth -= 1
            if depth == 0:
                return t[:i].rstrip(), t[i:]
    m = re.search(r"\s\((?:user|20\d\d-|same |the |ruling|amend|Option)", t)
    return (t[:m.start()].rstrip(), t[m.start():]) if m else (t, "")


def clean_title(rest):
    rest = rest.strip()
    rest = re.sub(r"^[\s.—–:-]+", "", rest)
    title, paren = strip_trailing_paren(rest)
    title = title.strip().rstrip(" —-–:")
    title = re.sub(r"\s+", " ", title)
    if len(title) > 120:
        title = title[:117].rstrip() + "…"
    return title, paren


def parse_sections(text):
    """[{num, line, title, paren, subs}] for every H2 section, in document
    order. Amendment/follow-up H2s and letter-suffixed H3s are counted on the
    section that owns them, not listed as rulings of their own."""
    sections, by_num, current = [], {}, None
    for i, line in enumerate(text.split("\n"), 1):
        m = SECTION_HEADING.match(line)
        if m:
            num, rest = m.group(1), m.group(2)
            if SUB_ENTRY.match(rest.lstrip(" .—-")):
                if num in by_num:
                    by_num[num]["subs"] += 1
                continue
            title, paren = clean_title(rest)
            s = {"num": num, "line": i, "title": title, "paren": paren, "subs": 0}
            sections.append(s)
            by_num[num] = s
            current = s
            continue
        if current is not None and SUB_HEADING.match(line):
            current["subs"] += 1
    # A bare "## §536" heading carries its title as the body's bold lead.
    lines = text.split("\n")
    for s in sections:
        if s["title"]:
            continue
        lead = " ".join(l.strip() for l in lines[s["line"]:s["line"] + 4]).strip()
        m = re.match(r"\*\*(.+?)(?:\*\*|$)", lead)
        if m:
            s["title"], _ = clean_title(m.group(1).rstrip("."))
    return sections, by_num


def split_top_level(cell):
    """Drop every parenthesized span (depth-aware) so a verb phrase about a
    DIFFERENT ruling, inside an explanation, is never read as this row's."""
    out, depth = [], 0
    for c in cell:
        if c == "(":
            depth += 1
            continue
        if c == ")":
            depth = max(0, depth - 1)
            continue
        if depth == 0:
            out.append(c)
    return "".join(out)


VERB_BY = re.compile(
    r"([\w'’ ]{0,30}?)\b(" + "|".join(sorted(KILL | AMEND, key=len, reverse=True)) +
    # The tail after the refs is a LOOKAHEAD: consuming it swallowed the next
    # verb, so "superseded by §97, reversed by §114" lost §114.
    r")\b([^§]{0,40}?)\bby\s+((?:§\d+[a-z]{0,2}(?:\s*(?:,|and|&)\s*)?)+)(?=([^,;—|]{0,40}))",
    re.I)


def _norm(x):
    return re.sub(r"[^a-z0-9 ]", "", x.lower().replace("—", " ")).split()


def title_matches(qual, title):
    """Does a row's description name the WHOLE ruling? Yes when it is the
    ruling's own title (a prefix either way, or most of its first words)."""
    q, t = _norm(qual), _norm(title)
    if not q or not t:
        return False
    qs, ts = " ".join(q), " ".join(t)
    # A PREFIX, never word overlap. "the box gives way" lies wholly inside
    # §772's title and "the tray's Manage is a room's one door" shares 7 of
    # 10 words with §937's — both are clauses, and both rulings stand. A
    # wrongly-kept clause costs a "part superseded" note; a wrongly-killed
    # ruling vanishes from the digest, so overlap never decides.
    return ts.startswith(qs[:20]) or qs.startswith(ts[:20])


def parse_targets(col1, by_num, what=""):
    """Col 1 of an index row → [(num, whole?)]. Whole only when the cell names
    the ruling bare, or names it by its own title."""
    out = []
    parts = re.split(r"\s+/\s+|\s+and\s+(?=§)", col1)
    for p in parts:
        p = p.strip().strip("*")
        refs = REF.findall(p)
        if not refs:
            continue
        # "§247 / §309 / §375 (the import rooms' …)" — the qualifier rides the
        # last part but describes them all, so a bare part is not "whole".
        m = re.match(r"^§(\d+[a-z]{0,2})\s*(?:\((.*)\))?\s*$", p)
        if m:
            num, qual = m.group(1), m.group(2)
            title = by_num[num]["title"] if num in by_num else ""
            if qual is None:
                # A bare number: whole only when "What it said" is the
                # ruling's own title — §500 has three bare rows, one per
                # clause, and none of them is the seat ruling's title.
                whole = len(parts) == 1 and title_matches(what, title)
            else:
                whole = title_matches(qual, title)
            out.append((num, whole))
        else:
            # "§548's tail order (…)", "§983 item 2 (…)", "§529 §4 (…)",
            # "§916 amendment (…)" — a clause.
            out.append((refs[0], False))
    return out


def parse_effects(col3):
    """Col 3 → [(kind, changer, partial)] read from TOP-LEVEL text only.
    kind is 'kill' or 'amend'. A kill is WHOLE only when its verb opens its
    clause ("superseded by §97", "amended by §36j, superseded by §36o"); a
    subject in front of the verb names the part that died ("default reversed
    by §393a", "the glass tray itself … deleted by §712", "Frames half
    reversed by §504")."""
    top = split_top_level(col3)
    effects = []
    # "…; §775 is in turn superseded by §904" is a fact about §775 riding this
    # row, not about the row's ruling — drop any clause whose subject is a §.
    own = ";".join(c for c in top.split(";")
                   if not re.match(r"\s*§\d+[a-z]{0,2}\s+(?:is|was|in turn|itself)\b", c))
    for m in VERB_BY.finditer(own):
        _, verb, between, refs, after = m.groups()
        verb = verb.lower()
        kind = "kill" if verb in KILL else "amend"
        head = own[:m.start(2)]
        cut = max(head.rfind(";"), head.rfind(","), head.rfind("—"), head.rfind(":"))
        subject = head[cut + 1:].strip().strip("*").strip()
        subject = re.sub(r"^(?:and then|and|then|later|since)\b", "", subject, flags=re.I).strip()
        partial = bool(subject
                       or PARTIAL_WORDS.search(between or "")
                       or re.match(r"\s*\**\s*(in the wallet|for |as the |only)", after or "", re.I))
        for r in REF.findall(refs):
            effects.append((kind, r, partial))
    if not effects:
        # Known-stale shape: "§100 — the tab bar was dropped …" (no verb).
        m = re.match(r"^\s*§(\d+[a-z]{0,2})\b", top)
        if m:
            effects.append(("kill", m.group(1), False))
    return effects


def index_rows(text):
    start = text.find(INDEX_START)
    if start < 0:
        return []
    end = text.find(INDEX_END, start)
    block = text[start:end if end > 0 else len(text)]
    rows = []
    for line in block.split("\n"):
        if not line.startswith("|") or re.match(r"^\|[\s|:-]+\|?$", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or cells[0] in ("Ruling", "Now"):
            continue
        rows.append((cells[0], cells[1], " | ".join(cells[2:])))
    return rows


HEAD_VERB = re.compile(
    r"\b(supersedes?|amends?|reverses?|overturns?|retires?|replaces?|extends?|"
    r"narrows?|withdraws?|deletes?)\b", re.I)
HEAD_PASSIVE = re.compile(
    r"\b(?:superseded|reversed|overturned|retired|withdrawn|replaced)\b[^;)§]{0,40}?\bby\s+§(\d+[a-z]{0,2})", re.I)
HEAD_REF = re.compile(r"(?:§)?(\d+[a-z]{0,2})\b(['’]s|\s+item\b|\s+for\b)?")


def header_effects(paren):
    """The heading's own parenthetical: "(…; supersedes §1008, amends §1011,
    §976a and §958)". Each verb owns the refs up to the next verb or ';'."""
    out = []
    if not paren:
        return out
    verbs = list(HEAD_VERB.finditer(paren))
    for k, vm in enumerate(verbs):
        stop = verbs[k + 1].start() if k + 1 < len(verbs) else len(paren)
        seg = paren[vm.end():stop]
        seg = re.split(r"[;)]", seg)[0]
        verb = vm.group(1).lower()
        kind = "amend" if verb.rstrip("s") in ("amend", "extend", "narrow") else "kill"
        # Only refs at the head of the segment, joined by , / and — so
        # "supersedes §729's commit row, follows §1027" stops at the clause.
        pos = 0
        seg_s = seg
        while True:
            mm = re.match(r"\s*(?:,|/|and|&)?\s*", seg_s[pos:])
            pos += mm.end()
            rm = HEAD_REF.match(seg_s, pos)
            if not rm or (not seg_s[pos:].startswith("§") and not re.match(r"\d+[a-z]{0,2}\b", seg_s[pos:])):
                break
            # A bare number must be a pre-§ section like "36a", never "2026".
            if not seg_s[pos:].startswith("§") and len(re.match(r"\d+", rm.group(1)).group(0)) > 3:
                break
            partial = bool(rm.group(2))
            out.append((kind, rm.group(1), partial))
            pos = rm.end()
            # Words after a ref and before the next separator make it a clause.
            tail = re.match(r"([^,/]*?)(?=\s*(?:,|/|\band\b|$))", seg_s[pos:])
            if tail and tail.group(1).strip():
                out[-1] = (kind, rm.group(1), True)
                pos += tail.end()
    return out


def compute(text, live_despite=None):
    """→ (sections, by_num, dead {num: [changers]}, notes {num: [(kind, by)]},
    renames {old: new})."""
    sections, by_num = parse_sections(text)
    dead, notes, renames = {}, {}, {}

    def note(num, kind, by):
        if num == by:
            return
        lst = notes.setdefault(num, [])
        if (kind, by) not in lst:
            lst.append((kind, by))

    for col1, col2, col3 in index_rows(text):
        # A pure renumber row: "| §236b | §236 | collided with … |".
        if re.fullmatch(r"§\d+[a-z]{0,2}", col1) and re.fullmatch(r"§\d+[a-z]{0,2}", col2):
            renames[col2[1:]] = col1[1:]
            continue
        targets = parse_targets(col1, by_num, col2)
        effects = parse_effects(col3)
        for num, whole in targets:
            for kind, by, partial in effects:
                if kind == "kill" and whole and not partial:
                    dead.setdefault(num, [])
                    if by not in dead[num]:
                        dead[num].append(by)
                elif kind == "kill":
                    note(num, "part superseded", by)
                else:
                    note(num, "amended", by)

    for s in sections:
        # PASSIVE, about the heading itself: "(recorded 2026-09-27; superseded
        # the next day by §969)" — the entry was written already dead.
        for pm in HEAD_PASSIVE.finditer(s["paren"]):
            dead.setdefault(s["num"], [])
            if pm.group(1) not in dead[s["num"]]:
                dead[s["num"]].append(pm.group(1))
        for kind, ref, partial in header_effects(s["paren"]):
            if ref == s["num"]:
                continue
            if kind == "kill" and not partial:
                dead.setdefault(ref, [])
                if s["num"] not in dead[ref]:
                    dead[ref].append(s["num"])
            elif kind == "kill":
                note(ref, "part superseded", s["num"])
            else:
                note(ref, "amended", s["num"])
    for num in (live_despite or {}):
        for by in dead.pop(num, []):
            note(num, "part superseded", by)
    return sections, by_num, dead, notes, renames


def sort_key(num):
    m = re.match(r"(\d+)([a-z]*)", num)
    return (int(m.group(1)), m.group(2))


