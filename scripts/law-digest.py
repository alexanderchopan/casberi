def hand_half_citations(hand):
    return set(REF.findall(hand))


def check_hand_half(hand, dead_set):
    """A rule in the by-area half that cites a ruling the ledger now records as
    dead is a stale rule. The 'Conflicts' and history lines may name dead
    rulings on purpose, so only lines that are rules (start with '- ') before
    the conflicts heading are checked."""
    bad = []
    body = hand.split("## Conflicts to resolve")[0]
    for ln in body.split("\n"):
        if not ln.lstrip().startswith("- "):
            continue
        for num in REF.findall(ln):
            if num in dead_set:
                bad.append((num, ln.strip()[:110]))
    return bad


