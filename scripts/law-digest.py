def chain_text(chain):
    part = sorted({b for k, b in chain if k == "part superseded"}, key=sort_key)
    amended = sorted({b for k, b in chain if k == "amended"} - set(part), key=sort_key)
    bits = []
    if amended:
        bits.append("amended by " + ", ".join("§" + b for b in amended))
    if part:
        bits.append("part superseded by " + ", ".join("§" + b for b in part))
    return f" ({'; '.join(bits)})" if bits else ""


def render(text, live_despite=None):
    sections, by_num, dead, notes, renames = compute(text, live_despite)
    live = [s for s in sections if s["num"] not in dead]
    lines = [MARKER, "",
             "## Live rulings, every one (generated)",
             "",
             f"{len(live)} of {len(sections)} H2 rulings in `docs/prd.md` are not superseded, "
             f"reversed, deleted or retired WHOLE by anything the ledger records "
             f"(the Superseded index, Known stale, Renumbered, and each heading's own "
             f"parenthetical). \"Part superseded\" means a CLAUSE of the ruling was "
             f"replaced — read the later entry before citing that clause. Numbers "
             f"1–33 are the original spec chapters. A ruling outgrown with no phrase "
             f"anywhere still reads as live here; the by-area section above is the "
             f"judgement layer.",
             ""]
    for s in sorted(live, key=lambda s: sort_key(s["num"])):
        sub = f" [+{s['subs']} sub-entries]" if s["subs"] else ""
        lines.append(f"- §{s['num']} — {s['title']}{chain_text(notes.get(s['num'], []))}{sub}")
    lines += ["", "## Dead rulings → what replaced them (generated)", "",
              "Superseded, reversed, deleted or retired whole. Read the right-hand "
              "entry instead; the left one is history.", ""]
    dead_known = sorted((n for n in dead if n in by_num), key=sort_key)
    lines.append(" · ".join(f"§{n}→{'/'.join('§' + b for b in sorted(dead[n], key=sort_key))}"
                            for n in dead_known))
    if renames:
        lines += ["", "## Renumbered (generated)", "",
                  " · ".join(f"§{old}→§{new}" for old, new in
                             sorted(renames.items(), key=lambda kv: sort_key(kv[0])))]
    lines.append("")
    return "\n".join(lines), {"total": len(sections), "live": len(live),
                              "dead": len(dead_known), "dead_set": set(dead_known),
                              "part": sum(1 for s in live if any(k == "part superseded" for k, _ in notes.get(s["num"], []))),
                              "amended": sum(1 for s in live if notes.get(s["num"]))}


