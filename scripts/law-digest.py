# A qualifier that turns a kill into a clause-kill, wherever it sits in the
# phrase: "superseded in part by", "Frames half reversed by", "superseded by
# §941 in the Wallet", "amended … for ONE event", "as the SURFACE only".
PARTIAL_WORDS = re.compile(
    r"\b(in part|in shape|half|item \d|items?|clause|default|for the|for those|"
    r"for one|for polar|for walletbeat|for [A-Z]|in the wallet|only|as the)\b", re.I)

