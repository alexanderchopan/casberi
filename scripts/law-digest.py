#!/usr/bin/env python3
"""The current-law digest (2026-10-01): which rulings in `docs/prd.md` are LIVE.

`docs/prd.md` is the append-only ruling ledger — a ruling that was reversed
stays exactly as written, so a dead entry looks exactly like a live one, and
"what is the rule today" means reading a chain. `docs/law.md` is the digest:
a hand-written "Current law by area" on top, and below it the MECHANICAL half
this script writes — every live ruling, one line, with the later rulings that
amend it.

WHERE "DEAD" COMES FROM — four sources, all inside the ledger itself:

  1. The Superseded index table (`| Ruling | What it said | Changed by |`).
  2. "Known stale, by hand" (rulings replaced without naming a number).
  3. "Renumbered entries" (a bare `| §236b | §236 | … |` row is a rename, not a
     change; the other rows that drifted into that table are read like 1/2).
  4. Each H2 heading's own parenthetical: "(…; supersedes §X, amends §Y)",
     "retires §Z", "reverses §W's one item", and the pre-§ spelling
     "supersedes 36a/36j".

THREE OUTCOMES, never two. A row or phrase that kills a ruling WHOLE removes it
from the live set. One that names a CLAUSE — "§548's tail order", "§983 item
2", "§306 (quiet hours)" where "quiet hours" is not §306's title, "superseded
in part", "for Polar only", "in the Wallet" — leaves the ruling live and marks
it "part superseded by §N", because guessing that a clause was the whole ruling
is how a live rule silently vanishes from the digest. Amend/extend/narrow is
always a chain link, never a death. Verb phrases INSIDE a parenthesis in an
index row are skipped: "(…; §775 is in turn superseded by §904)" is a fact
about §775 riding §772's row, not a fact about §772.

DELIBERATE NON-CHECKS:
  * It never reads an entry's BODY for supersede phrases. `prd-index-audit.py`
    check D already fails the build when a body names "supersedes §N" without an
    index row, so the index IS the body's claims, tabulated.
  * It cannot see a ruling quietly outgrown with no phrase anywhere. That is
    what the hand-written half above the marker and the "Known stale" table
    exist for.

Usage:
  python3 scripts/law-digest.py            rewrite docs/law.md below the marker
  python3 scripts/law-digest.py --check    exit 1 if law.md is stale, or if the
                                           hand-written half cites a ruling the
                                           ledger now says is dead
  python3 scripts/law-digest.py --self-test
  python3 scripts/law-digest.py --stats    counts only

Stdlib only.
"""

