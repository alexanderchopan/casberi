#!/usr/bin/env python3
"""hosts-doc.py — docs/hosts.md, every host the app is declared to contact.

The list already exists in code: `Casberi/Casberi/Model/NetworkReach.swift`
declares every service, why it is reached and its hosts, and
`scripts/network-reach-audit.sh` fails the build on a host literal that is not
declared there. This writes that registry out as a page a person can read
without opening Swift.

  hosts-doc.py            write docs/hosts.md
  hosts-doc.py --check    exit 1 when docs/hosts.md is stale
  hosts-doc.py --self-test
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "Casberi", "Casberi", "Model", "NetworkReach.swift")
OUT = os.path.join(ROOT, "docs", "hosts.md")


def strip_comments(text):
    """Drop // comments, keeping string literals whole (a URL holds `//`)."""
    out, i, in_str = [], 0, False
    while i < len(text):
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < len(text):
                out.append(text[i + 1]); i += 2; continue
            if c == '"':
                in_str = False
        elif c == '"':
            in_str = True; out.append(c)
        elif text.startswith("//", i):
            while i < len(text) and text[i] != "\n":
                i += 1
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def entries(text):
    """Each `Endpoint( … )` body, by matching parentheses outside strings."""
    text = strip_comments(text)
    found, at = [], 0
    while True:
        start = text.find("Endpoint(service:", at)
        if start < 0:
            return found
        i, depth, in_str = start + len("Endpoint"), 0, False
        while i < len(text):
            c = text[i]
            if in_str:
                if c == "\\":
                    i += 2; continue
                if c == '"':
                    in_str = False
            elif c == '"':
                in_str = True
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        found.append(text[start:i + 1])
        at = i + 1


STRING = r'"((?:[^"\\]|\\.)*)"'


def strings(body, label):
    m = re.search(label + r":\s*\[(.*?)\]", body, re.S)
    return re.findall(STRING, m.group(1)) if m else []


def joined(body, label):
    """A string argument, which Swift may split across lines with `+`."""
    m = re.search(label + r":\s*((?:" + STRING + r"\s*\+?\s*)+)", body, re.S)
    if not m:
        return ""
    return "".join(re.findall(STRING, m.group(1)))


def plain(s):
    s = s.replace("\\(DS.device)", "This device").replace('\\"', '"')
    s = re.sub(r"\\\(([^)]*)\)", r"\1", s)
    return s.replace("|", "\\|").replace("\n", " ").strip()


def parse(text):
    rows = []
    for body in entries(text):
        service = re.search(r"Endpoint\(service:\s*" + STRING, body).group(1)
        if ".always" in body.split("purpose:")[0]:
            when = "Always"
        elif ".onTapWithKey" in body.split("purpose:")[0]:
            when = "Only with your own agent key, on a tap"
        else:
            bridge = re.search(r"\.whenConnected\(bridge:\s*" + STRING, body)
            when = f"When {bridge.group(1)} is connected" if bridge else "When connected"
        rows.append({
            "service": service,
            "when": when,
            "purpose": plain(joined(body, "purpose")),
            "hosts": strings(body, "hosts"),
            "tor": bool(re.search(r"throughTor:\s*true", body)),
            "refuses": strings(body, "refusesTor"),
        })
    return rows


def render(rows):
    always = [r for r in rows if r["when"] == "Always"]
    rest = [r for r in rows if r["when"] != "Always"]
    hosts = sorted({h for r in rows for h in r["hosts"] if "." in h and " " not in h})
    out = [
        "# Every host the app contacts",
        "",
        "Generated by `scripts/hosts-doc.py` from `Casberi/Casberi/Model/NetworkReach.swift`. Do not edit by hand.",
        "",
        "Casberi has no server. Every request goes from the device straight to the service it names, and this is the whole list: "
        f"{len(rows)} services, {len(hosts)} named hosts. `scripts/network-reach-audit.sh` fails the build on a host in the source that is not declared here, "
        "and the app records the hosts it actually reached so the two can be compared (in the app: What this app reaches).",
        "",
        "Two kinds of host cannot be listed by name: one that comes from your own input (a feed you follow, your own node), and one a "
        "vendored SDK builds at runtime. Those rows say so in words.",
        "",
        "\"Through Tor\" applies on iPhone and iPad. The Mac build has no Tor and reads directly.",
        "",
    ]

    def table(title, group, note):
        out.extend([f"## {title}", "", note, "", "| Service | When | What the calls are for | Hosts | Through Tor |", "| --- | --- | --- | --- | --- |"])
        for r in sorted(group, key=lambda r: r["service"].lower()):
            listed = ", ".join(f"`{h}`" if "." in h and " " not in h else h for h in r["hosts"]) or "none listed"
            tor = "Yes" if r["tor"] else "No"
            if r["refuses"]:
                tor += " (direct for " + ", ".join(f"`{h}`" for h in r["refuses"]) + ", which refuse Tor)"
            out.append(f"| {r['service']} | {r['when']} | {r['purpose']} | {listed} | {tor} |")
        out.append("")

    table("Reached without connecting anything", always, f"{len(always)} services.")
    table("Reached only for something you connected or asked for", rest, f"{len(rest)} services. Nothing here is contacted until its app is connected.")
    return "\n".join(out)


def self_test():
    sample = '''
    static let shipped: [Endpoint] = [
        // A comment with Endpoint(service: "Ghost", hosts: ["ghost.example"]) in it.
        Endpoint(service: "Saved links",
                 reach: .always,
                 purpose: "Reads a page (once) at https://example.com/a, "
                        + "for \\(DS.device).",
                 hosts: ["the page you saved"]),
        Endpoint(service: "Wallet",
                 reach: .whenConnected(bridge: "Wallet"),
                 purpose: "Balances.",
                 // both spellings
                 hosts: ["api.one.example", "two.example"],
                 throughTor: true,
                 refusesTor: ["two.example"]),
    ]'''
    rows = parse(sample)
    checks = [
        (len(rows) == 2, "a commented-out entry is not an entry"),
        (rows[0]["service"] == "Saved links" and rows[0]["when"] == "Always", "an always-on entry"),
        (rows[0]["purpose"] == "Reads a page (once) at https://example.com/a, for This device.", "a purpose split with + and holding // and parentheses"),
        (rows[1]["when"] == "When Wallet is connected", "a connected entry names its app"),
        (rows[1]["hosts"] == ["api.one.example", "two.example"], "hosts survive a comment inside the entry"),
        (rows[1]["tor"] and rows[1]["refuses"] == ["two.example"], "Tor and its refusals are read"),
        ("`api.one.example`" in render(rows) and "the page you saved" in render(rows), "a prose host is not dressed as a hostname"),
    ]
    failed = [what for ok, what in checks if not ok]
    for ok, what in checks:
        print(("  ✓ " if ok else "  ✗ ") + what)
    print("✓ hosts-doc self-test passed" if not failed else f"✗ hosts-doc self-test: {len(failed)} failed")
    return 1 if failed else 0


def main():
    if "--self-test" in sys.argv:
        return self_test()
    rows = parse(open(SOURCE, encoding="utf-8").read())
    if len(rows) < 50:
        print(f"✗ hosts-doc: only {len(rows)} entries parsed from NetworkReach.swift; the parser no longer fits the file")
        return 1
    page = render(rows) + "\n"
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != page:
            print("✗ docs/hosts.md is stale — run `python3 scripts/hosts-doc.py`")
            return 1
        print(f"✓ hosts page current: {len(rows)} services")
        return 0
    open(OUT, "w", encoding="utf-8").write(page)
    print(f"hosts-doc: wrote docs/hosts.md ({len(rows)} services)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
