// Writes Casberi/Casberi/Model/PrivacyArtifactPins.swift: the SHA-256 of
// every circuit file the engine may run, per network (prd §1540). The app
// refuses any byte that does not hash to its pin.
//
// Sepolia's verifiers were built from the single-contributor DEV keys that
// @0xbow/privacy-pools-v2-sdk@1.0.0 shipped; 1.0.1 and later ship the
// trusted-setup ceremony keys, which only mainnet verifies (measured
// 2026-10-26 by matching the deposit vkey's constants in the Sepolia
// verifier's bytecode). So the Sepolia pins are 1.0.0's manifest, read here
// from that exact published tarball.
//
// Ethereum's verifiers hold the CEREMONY keys (prd §1563): 1.0.2's manifest,
// the version the engine bundles. Proven by `mainnet-sim.mjs`: a deposit and
// a ragequit proved with these files verify against mainnet's own verifiers
// in simulation, and the same deposit proved with Sepolia's dev keys reverts.
//   node pins.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../Casberi/Casberi/Model/PrivacyArtifactPins.swift');

function manifestOf(version) {
  const dir = mkdtempSync(join(tmpdir(), 'pp-sdk-'));
  const tgz = execFileSync('npm', ['pack', `@0xbow/privacy-pools-v2-sdk@${version}`, '--silent'], { cwd: dir }).toString().trim();
  execFileSync('tar', ['xzf', tgz], { cwd: dir });
  const src = readFileSync(join(dir, 'package/dist/index.js'), 'utf8');
  const start = src.indexOf('var DEFAULT_CIRCUIT_MANIFEST = {');
  if (start < 0) throw new Error(`no manifest in ${version}`);
  const body = src.slice(start, src.indexOf('\n};', start));
  const entries = {};
  for (const m of body.matchAll(/(\w+): \{([^}]*)\}/g)) {
    const fields = Object.fromEntries([...m[2].matchAll(/(\w+): "([^"]*)"/g)].map((f) => [f[1], f[2]]));
    entries[m[1]] = fields;
  }
  return entries;
}

const sepolia = manifestOf('1.0.0');
const ceremony = manifestOf('1.0.2');
const names = Object.keys(sepolia).sort((a, b) => (a === 'deposit' ? -1 : b === 'deposit' ? 1 : a < b ? -1 : 1));
if (names.length !== 27) throw new Error(`expected 27 circuits, read ${names.length}`);
const row = (name, e) => {
  for (const k of ['wasm', 'wasmSha256', 'provingKey', 'provingKeySha256', 'verificationKey', 'verificationKeySha256']) {
    if (!e[k]) throw new Error(`${name}.${k} missing`);
  }
  return `        "${name}": Circuit(\n` +
    `            wasm: File(cid: "${e.wasm}", sha256: "${e.wasmSha256}"),\n` +
    `            zkey: File(cid: "${e.provingKey}", sha256: "${e.provingKeySha256}"),\n` +
    `            vkey: File(cid: "${e.verificationKey}", sha256: "${e.verificationKeySha256}")),`;
};
if (Object.keys(ceremony).length !== 27) throw new Error(`expected 27 ceremony circuits, read ${Object.keys(ceremony).length}`);
const swift = `// GENERATED by tools/privacy-pools-engine/pins.mjs — do not edit by hand.
//
// The circuit files the Privacy Pools engine may run (prd §1540, §1563).
// Sepolia: @0xbow/privacy-pools-v2-sdk@1.0.0's manifest, the DEV keys
// Sepolia's verifiers were built from. Ethereum: 1.0.2's manifest, the
// trusted-setup CEREMONY keys mainnet's verifiers hold. Each file is fetched
// by its IPFS CID and refused unless it hashes to its SHA-256 here
// (\`PrivacyArtifacts.verify\`).

extension PrivacyArtifacts {
    static let sepoliaPins: [String: Circuit] = [
${names.map((n) => row(n, sepolia[n])).join('\n')}
    ]

    static let ceremonyPins: [String: Circuit] = [
${names.map((n) => row(n, ceremony[n])).join('\n')}
    ]
}
`;
writeFileSync(out, swift);
console.log(`wrote ${names.length} circuits to ${out}`);
