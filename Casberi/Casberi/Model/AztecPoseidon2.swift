import Foundation

/// Poseidon2 over BN254's scalar field — the hash every Aztec storage slot,
/// argument hash and signed payload is built from (2026-10-11). Foundation
/// only, so `scripts/aztec-selftest.sh` compiles it WHOLE against vectors
/// measured off aztec.js and Aztec's own Barretenberg.
///
/// **Why native.** Barretenberg ships an iOS static library that computes
/// this exactly (measured: it rebuilt a mined transaction's signed hash), but
/// it links ~21 MB into the app for one hash. This is that hash alone: the
/// t = 4 permutation (8 full rounds, 56 partial, x⁵ S-box) and the rate-3
/// sponge whose IV is the input length shifted left 64 bits — Barretenberg's
/// `poseidon2_permutation.hpp` and `sponge.hpp`, line for line.
enum AztecPoseidon2 {

    /// A field element: four little-endian 64-bit limbs, Montgomery form.
    struct Fr: Equatable {
        fileprivate var l: (UInt64, UInt64, UInt64, UInt64)
        static func == (a: Fr, b: Fr) -> Bool { a.l == b.l }
    }

    // MARK: - Public surface

    /// `poseidon2HashWithSeparator(inputs, separator)`: the separator is the
    /// first input.
    static func hash(_ inputs: [Data], separator: UInt32) -> Data {
        hash([Data(bigEndian: UInt64(separator))] + inputs)
    }

    /// `poseidon2Hash(inputs)`. Each input is a big-endian field element of
    /// up to 32 bytes; a value at or past the modulus is reduced, as the
    /// reference reduces it.
    static func hash(_ inputs: [Data]) -> Data {
        var state = [Fr](repeating: zero, count: 4)
        state[3] = fromInt(UInt64(inputs.count), shift64: true)
        var cache: [Fr] = []
        for input in inputs {
            if cache.count == 3 { duplex(&state, cache); cache = [] }
            cache.append(element(input))
        }
        duplex(&state, cache)
        return bytes(state[0])
    }

    // MARK: - Sponge and permutation

    private static func duplex(_ state: inout [Fr], _ cache: [Fr]) {
        for (i, c) in cache.enumerated() { state[i] = add(state[i], c) }
        permute(&state)
    }

    static func permute(_ s: inout [Fr]) {
        external(&s)
        for r in 0..<4 { full(&s, r) }
        for r in 4..<60 {
            s[0] = add(s[0], roundConstants[r][0])
            s[0] = sbox(s[0])
            internalLayer(&s)
        }
        for r in 60..<64 { full(&s, r) }
    }

    private static func full(_ s: inout [Fr], _ r: Int) {
        for i in 0..<4 { s[i] = sbox(add(s[i], roundConstants[r][i])) }
        external(&s)
    }

    private static func sbox(_ x: Fr) -> Fr {
        let x2 = mul(x, x)
        let x4 = mul(x2, x2)
        return mul(x4, x)
    }

    /// The 4×4 external matrix, Barretenberg's addition chain.
    private static func external(_ s: inout [Fr]) {
        let t0 = add(s[0], s[1]), t1 = add(s[2], s[3])
        var t2 = add(s[1], s[1]); t2 = add(t2, t1)
        var t3 = add(s[3], s[3]); t3 = add(t3, t0)
        var t4 = add(t1, t1); t4 = add(t4, t4); t4 = add(t4, t3)
        var t5 = add(t0, t0); t5 = add(t5, t5); t5 = add(t5, t2)
        let t6 = add(t3, t5), t7 = add(t2, t4)
        s = [t6, t5, t7, t4]
    }

    private static func internalLayer(_ s: inout [Fr]) {
        let sum = add(add(s[0], s[1]), add(s[2], s[3]))
        for i in 0..<4 { s[i] = add(mul(s[i], diagonalMinusOne[i]), sum) }
    }

    // MARK: - BN254 scalar field, Montgomery form

    /// p = 0x30644e72e131a029b85045b68181585d2833e84879b9709143e1f593f0000001
    private static let p: (UInt64, UInt64, UInt64, UInt64) =
        (0x43e1f593f0000001, 0x2833e84879b97091, 0xb85045b68181585d, 0x30644e72e131a029)
    /// −p⁻¹ mod 2⁶⁴.
    private static let inv: UInt64 = 0xc2e1f593efffffff
    /// R² mod p, R = 2²⁵⁶: what lifts a plain value into Montgomery form.
    private static let r2 = Fr(l: (0x1bb8e645ae216da7, 0x53fe3ab1e35c59e3, 0x8c49833d53bb8085, 0x0216d0b17f4e44a5))
    private static let zero = Fr(l: (0, 0, 0, 0))

    private static func limbs(_ a: Fr) -> [UInt64] { [a.l.0, a.l.1, a.l.2, a.l.3] }
    private static func fr(_ a: [UInt64]) -> Fr { Fr(l: (a[0], a[1], a[2], a[3])) }
    private static let pl: [UInt64] = [p.0, p.1, p.2, p.3]

    private static func geqP(_ a: [UInt64]) -> Bool {
        for i in stride(from: 3, through: 0, by: -1) where a[i] != pl[i] { return a[i] > pl[i] }
        return true
    }

    private static func subP(_ a: [UInt64]) -> [UInt64] {
        var out = [UInt64](repeating: 0, count: 4)
        var borrow: UInt64 = 0
        for i in 0..<4 {
            let (d1, o1) = a[i].subtractingReportingOverflow(pl[i])
            let (d2, o2) = d1.subtractingReportingOverflow(borrow)
            out[i] = d2
            borrow = (o1 ? 1 : 0) + (o2 ? 1 : 0)
        }
        return out
    }

    static func add(_ a: Fr, _ b: Fr) -> Fr {
        let x = limbs(a), y = limbs(b)
        var out = [UInt64](repeating: 0, count: 4)
        var carry: UInt64 = 0
        for i in 0..<4 {
            let (s1, o1) = x[i].addingReportingOverflow(y[i])
            let (s2, o2) = s1.addingReportingOverflow(carry)
            out[i] = s2
            carry = (o1 ? 1 : 0) + (o2 ? 1 : 0)
        }
        // p < 2²⁵⁴, so a + b never carries out of the top limb.
        return fr(geqP(out) ? subP(out) : out)
    }

    /// Montgomery product a·b·R⁻¹ (CIOS).
    static func mul(_ a: Fr, _ b: Fr) -> Fr {
        let x = limbs(a), y = limbs(b)
        var t = [UInt64](repeating: 0, count: 6)
        for i in 0..<4 {
            var carry: UInt64 = 0
            for j in 0..<4 {
                let (hi, lo) = x[j].multipliedFullWidth(by: y[i])
                let (s1, o1) = t[j].addingReportingOverflow(lo)
                let (s2, o2) = s1.addingReportingOverflow(carry)
                t[j] = s2
                carry = hi &+ (o1 ? 1 : 0) &+ (o2 ? 1 : 0)
            }
            let (s4, o4) = t[4].addingReportingOverflow(carry)
            t[4] = s4
            t[5] = o4 ? 1 : 0

            let m = t[0] &* inv
            let (hi0, lo0) = m.multipliedFullWidth(by: pl[0])
            let (_, oz) = t[0].addingReportingOverflow(lo0)
            carry = hi0 &+ (oz ? 1 : 0)
            for j in 1..<4 {
                let (hi, lo) = m.multipliedFullWidth(by: pl[j])
                let (s1, o1) = t[j].addingReportingOverflow(lo)
                let (s2, o2) = s1.addingReportingOverflow(carry)
                t[j - 1] = s2
                carry = hi &+ (o1 ? 1 : 0) &+ (o2 ? 1 : 0)
            }
            let (s5, o5) = t[4].addingReportingOverflow(carry)
            t[3] = s5
            t[4] = t[5] &+ (o5 ? 1 : 0)
        }
        let out = Array(t[0..<4])
        return fr(t[4] != 0 || geqP(out) ? subP(out) : out)
    }

    // MARK: - In and out

    /// A big-endian value of up to 32 bytes, reduced and lifted into
    /// Montgomery form.
    static func element(_ data: Data) -> Fr {
        let bytes = [UInt8](repeating: 0, count: max(0, 32 - data.count)) + [UInt8](data.suffix(32))
        var a = [UInt64](repeating: 0, count: 4)
        for i in 0..<4 {
            var limb: UInt64 = 0
            for b in bytes[(24 - 8 * i)..<(32 - 8 * i)] { limb = limb << 8 | UInt64(b) }
            a[i] = limb
        }
        while geqP(a) { a = subP(a) }
        return mul(fr(a), r2)
    }

    private static func fromInt(_ n: UInt64, shift64: Bool) -> Fr {
        mul(fr(shift64 ? [0, n, 0, 0] : [n, 0, 0, 0]), r2)
    }

    /// Back out of Montgomery form, big-endian, 32 bytes.
    static func bytes(_ a: Fr) -> Data {
        let plain = limbs(mul(a, Fr(l: (1, 0, 0, 0))))
        var out = Data()
        for i in stride(from: 3, through: 0, by: -1) {
            for s in stride(from: 56, through: 0, by: -8) { out.append(UInt8((plain[i] >> UInt64(s)) & 0xff)) }
        }
        return out
    }

    static func hex(_ data: Data) -> String { "0x" + data.map { String(format: "%02x", $0) }.joined() }

    /// A hex field ("0x…", any length up to 64 digits) as 32 bytes.
    static func field(_ hex: String) -> Data? {
        var s = hex.hasPrefix("0x") ? String(hex.dropFirst(2)) : hex
        guard s.count <= 64, s.allSatisfy(\.isHexDigit) else { return nil }
        s = String(repeating: "0", count: 64 - s.count) + s
        var out = Data()
        var i = s.startIndex
        while i < s.endIndex {
            let j = s.index(i, offsetBy: 2)
            out.append(UInt8(s[i..<j], radix: 16)!)
            i = j
        }
        return out
    }

